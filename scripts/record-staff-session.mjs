/**
 * Records an authenticated browser state for the Staff-surface Playwright tests.
 *
 * Two modes, because the right one depends on what you have:
 *
 *   1. Credentials in the environment - signs in through the real form, which
 *      exercises the actual auth path rather than injecting a token:
 *        E2E_STAFF_EMAIL=... E2E_STAFF_PASSWORD=... npm run test:e2e:record-auth
 *
 *   2. No credentials - opens a visible browser and waits for you to sign in by
 *      hand, then saves whatever session results:
 *        npm run test:e2e:record-auth
 *
 * The output lands in `e2e/.auth/staff.json`, which is git-ignored. It is a real
 * session token and must never be committed.
 *
 * When it is absent the staff tests skip with a message rather than failing, so
 * the suite stays runnable on a machine that has no credentials, and nobody is
 * tempted to hardcode a password to make it green.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { chromium } from "@playwright/test";

const PORT = process.env["PLAYWRIGHT_PORT"] ?? "8080";
const BASE_URL = process.env["PLAYWRIGHT_BASE_URL"] ?? `http://localhost:${PORT}`;
const OUT_DIR = join(import.meta.dirname, "..", "e2e", ".auth");
const OUT_FILE = join(OUT_DIR, "staff.json");

const email = process.env["E2E_STAFF_EMAIL"];
const password = process.env["E2E_STAFF_PASSWORD"];
const manual = !email || !password;

const browser = await chromium.launch({ headless: !manual });
const context = await browser.newContext();
const page = await context.newPage();

await page.goto(`${BASE_URL}/auth`, { waitUntil: "load" });

if (manual) {
  console.log("\nNo E2E_STAFF_EMAIL / E2E_STAFF_PASSWORD set.");
  console.log("A browser window is open. Sign in there, then come back to this terminal.\n");
} else {
  await page.fill("#email", email);
  await page.fill("#password", password);
  await page.click("button:has-text('Sign in')");
}

// Either path waits on the same observable: the session appearing in local
// storage as a Supabase auth token. Waiting on a selector would be brittle;
// waiting on the actual stored session is what the tests depend on.
await page
  .waitForFunction(
    () => {
      for (const key of Object.keys(localStorage)) {
        if (key.includes("auth-token") && localStorage.getItem(key)?.includes("access_token")) {
          return true;
        }
      }
      return false;
    },
    { timeout: manual ? 300_000 : 30_000 },
  )
  .catch(() => {
    console.error(
      "\nNo session appeared. Nothing was written.\n" +
        (manual
          ? "The window may have been closed before sign-in completed.\n"
          : "Check the credentials - sign-in may have failed.\n"),
    );
    process.exitCode = 1;
  });

if (process.exitCode !== 1) {
  mkdirSync(OUT_DIR, { recursive: true });
  await context.storageState({ path: OUT_FILE });
  writeFileSync(
    `${OUT_FILE}.readme`,
    "Generated by `npm run test:e2e:record-auth`. Git-ignored. Contains a live session token - do not commit.\n",
  );
  console.log(`\nSession saved to ${OUT_FILE}\nStaff-surface Playwright tests will now run.\n`);
}

await browser.close();
